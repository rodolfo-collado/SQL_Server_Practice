WITH CONSUMO_NACIONAL AS
(
    SELECT DIA, ZONA, ANTENA, MB
    FROM BD_REGION_1.dbo.CONSUMO_REGIONAL
    UNION ALL
    SELECT DIA, ZONA, ANTENA, MB
    FROM BD_REGION_2.dbo.CONSUMO_REGIONAL
    UNION ALL
    SELECT DIA, ZONA, ANTENA, MB
    FROM [SERVIDOR_REGION3].[BD_REGION_3].[dbo].[CONSUMO_REGIONAL]
),
RESUMEN AS
(
    SELECT
        DIA / 100 AS PERIODO,
        ZONA,
        ANTENA,
        SUM(MB) AS TOTAL_MB
    FROM CONSUMO_NACIONAL
    GROUP BY DIA / 100, ZONA, ANTENA
),
RANKING AS
(
    SELECT
        PERIODO,
        ZONA,
        ANTENA,
        TOTAL_MB,
        ROW_NUMBER() OVER
        (
            PARTITION BY PERIODO, ZONA
            ORDER BY TOTAL_MB DESC, ANTENA
        ) AS POSICION
    FROM RESUMEN
)
SELECT
    PERIODO,
    ZONA,
    POSICION,
    ANTENA,
    TOTAL_MB
FROM RANKING
WHERE POSICION <= 5
ORDER BY PERIODO, ZONA, POSICION;


