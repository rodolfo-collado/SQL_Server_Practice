WITH CONSUMO_NACIONAL AS
(
    SELECT DIA, ZONA, MB, MINUTOS, INGRESO
    FROM BD_REGION_1.dbo.CONSUMO_REGIONAL
    UNION ALL
    SELECT DIA, ZONA, MB, MINUTOS, INGRESO
    FROM BD_REGION_2.dbo.CONSUMO_REGIONAL
    UNION ALL
    SELECT DIA, ZONA, MB, MINUTOS, INGRESO
    FROM [SERVIDOR_REGION3].[BD_REGION_3].[dbo].[CONSUMO_REGIONAL]
),
RESUMEN AS
(
    SELECT
        DIA / 100 AS PERIODO,
        ZONA,

        SUM(MB) AS TOTAL_MB,
        AVG(MB) AS PROMEDIO_MB,
        MIN(MB) AS MIN_MB,
        MAX(MB) AS MAX_MB,

        SUM(MINUTOS) AS TOTAL_MINUTOS,

        SUM(INGRESO) AS TOTAL_INGRESO,
        AVG(INGRESO) AS PROMEDIO_INGRESO,
        MIN(INGRESO) AS MIN_INGRESO,
        MAX(INGRESO) AS MAX_INGRESO,

        SUM(CASE WHEN MB = 0 THEN 1 ELSE 0 END) AS SIN_CONSUMO,
        SUM(CASE WHEN MB > 0 AND MB <= 100 THEN 1 ELSE 0 END)
            AS CONSUMO_BAJO,
        SUM(CASE WHEN MB > 100 AND MB <= 500 THEN 1 ELSE 0 END)
            AS CONSUMO_MEDIO,
        SUM(CASE WHEN MB > 500 THEN 1 ELSE 0 END)
            AS CONSUMO_ALTO

    FROM CONSUMO_NACIONAL
    GROUP BY DIA / 100, ZONA
),
RANKING AS
(
    SELECT
        *,
        ROW_NUMBER() OVER
        (
            PARTITION BY PERIODO
            ORDER BY TOTAL_MB DESC, ZONA
        ) AS POSICION_MB
    FROM RESUMEN
)
SELECT
    PERIODO,
    POSICION_MB,
    ZONA,
    TOTAL_MB,
    PROMEDIO_MB,
    MIN_MB,
    MAX_MB,
    TOTAL_MINUTOS,
    TOTAL_INGRESO,
    PROMEDIO_INGRESO,
    MIN_INGRESO,
    MAX_INGRESO,
    SIN_CONSUMO,
    CONSUMO_BAJO,
    CONSUMO_MEDIO,
    CONSUMO_ALTO,

    CASE
        WHEN POSICION_MB = 1 THEN 'ZONA LIDER EN TRAFICO'
        WHEN POSICION_MB <= 3 THEN 'TRAFICO ALTO'
        ELSE 'TRAFICO RESTANTE'
    END AS CLASIFICACION_ZONA

FROM RANKING
ORDER BY PERIODO, POSICION_MB;


